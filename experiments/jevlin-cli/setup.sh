#!/usr/bin/env bash
# Prepare the jevlin_cli arm: a released jevlin binary and a benchmark-only client config.
#
#   experiments/jevlin-cli/setup.sh build  [JEVLIN_GO_DIR] [REF]   # builds REF (default v0.1.0) into runs/bin/jevlin
#   experiments/jevlin-cli/setup.sh config                         # writes runs/jevlin-cli/jevlin.toml + state (mining off)
#
# The config points the client at $JEVLIN_API_URL (same host as the HTTP arms); the key comes
# from $JEVLIN_API_KEY in the harness's .env, which the client reads from the environment, so no
# credentials file is written. Mining is disabled through the client's own persisted decision
# (state/mining_decision.json), the same way the A/B experiment did it. Nothing under ~/.jevlin is touched.
set -euo pipefail
cd "$(dirname "$0")/../.."
ROOT="$(pwd)"
BIN="$ROOT/runs/bin/jevlin"
HOME_DIR="$ROOT/runs/jevlin-cli"

case "${1:-}" in
  build)
    JEVLIN_GO_DIR="${2:-$HOME/Github/jevlin-go}"
    REF="${3:-v0.1.0}"
    WORK="$(mktemp -d)/jevlin-$REF"
    git -C "$JEVLIN_GO_DIR" worktree add --detach "$WORK" "$REF"
    trap 'git -C "$JEVLIN_GO_DIR" worktree remove --force "$WORK" 2>/dev/null || true' EXIT
    mkdir -p "$(dirname "$BIN")"
    GOTOOLCHAIN=auto go -C "$WORK" build -trimpath -o "$BIN" ./cmd/jevlin
    echo "built $BIN from $REF"
    go version -m "$BIN" | grep -E "^\s+(mod|build\s+vcs)" || true
    "$BIN" version
    ;;
  config)
    : "${JEVLIN_API_URL:?set JEVLIN_API_URL (same host as the HTTP arms)}"
    mkdir -p "$HOME_DIR/state" "$HOME_DIR/spool" "$HOME_DIR/intake" "$HOME_DIR/sessions"
    chmod 700 "$HOME_DIR/state"
    cat > "$HOME_DIR/jevlin.toml" <<EOF
# Benchmark-only jevlin config (jevlin_cli arm). Generated by experiments/jevlin-cli/setup.sh.
[[provider]]
name     = "search-router"
upstream = "${JEVLIN_API_URL%/}"

# enabled = false switches off only the mining machinery (spool flush, recording a search for
# rewards); the search path and what the model is shown do not read it. With it on, the client
# requires a [mining] block naming the rewards server, which a benchmark has no business touching.
[miner]
enabled      = false
intake_dir   = "$HOME_DIR/intake"
sessions_dir = "$HOME_DIR/sessions"

[mining]
state_dir = "$HOME_DIR/state"
spool_dir = "$HOME_DIR/spool"
EOF
    printf '{"version":1,"enabled":false}\n' > "$HOME_DIR/state/mining_decision.json"
    chmod 600 "$HOME_DIR/state/mining_decision.json"
    echo "wrote $HOME_DIR/jevlin.toml (mining disabled). Add to .env:"
    echo "JEVLIN_CLI_CONFIG=$HOME_DIR/jevlin.toml"
    echo "JEVLIN_BIN=$BIN"
    echo "(JEVLIN_CLI_CONFIG, not JEVLIN_CONFIG: a JEVLIN_CONFIG exported by the operator's shell would win over .env.)"
    ;;
  *)
    echo "usage: $0 build [JEVLIN_GO_DIR] [REF] | config" >&2
    exit 2
    ;;
esac
